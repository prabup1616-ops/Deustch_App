def db_save_repo_questions(topic: str, category: str, questions_list: List[Dict[str, Any]], created_by: str = "ai") -> int:
    """
    Saves a batch of Goethe B1 questions under a specific topic in the questions_repo.
    Returns the count of successfully inserted questions.
    """
    conn = _get_connection()
    if not conn or not questions_list:
        return 0
    clean_topic = topic.strip()
    inserted = 0
    try:
        with conn.cursor() as cur:
            for q in questions_list:
                cur.execute("""
                INSERT INTO questions_repo (topic, category, question_data, created_by)
                VALUES (%s, %s, %s, %s);
                """, (clean_topic, category, Json(q), created_by))
                inserted += 1
        conn.commit()
        return inserted
    except Exception as e:
        logger.error(f"db_save_repo_questions error: {e}")
        conn.rollback()
        return 0
    finally:
        conn.close()


def db_get_repo_questions(topic: str, category: str = "pronoun") -> List[Dict[str, Any]]:
    """
    Fetches all stored questions for a given topic from the questions_repo table.
    """
    conn = _get_connection()
    if not conn:
        return []
    clean_topic = topic.strip()
    try:
        with conn.cursor(cursor_factory=RealDictCursor) as cur:
            cur.execute("""
            SELECT id, topic, category, question_data, created_by, created_at
            FROM questions_repo
            WHERE LOWER(topic) = LOWER(%s) AND category = %s
            ORDER BY id ASC;
            """, (clean_topic, category))
            rows = cur.fetchall()
            results = []
            for r in rows:
                qdata = r.get("question_data", {})
                if isinstance(qdata, str):
                    try:
                        qdata = json.loads(qdata)
                    except Exception:
                        continue
                if isinstance(qdata, dict):
                    if "id" not in qdata:
                        qdata["id"] = r["id"]
                    if "topic" not in qdata:
                        qdata["topic"] = r["topic"]
                    results.append(qdata)
            return results
    except Exception as e:
        logger.error(f"db_get_repo_questions error: {e}")
        return []
    finally:
        conn.close()


def db_get_all_community_topics(category: str = "pronoun") -> List[str]:
    """
    Fetches all distinct grammar topics unlocked across all players and in questions_repo.
    """
    conn = _get_connection()
    if not conn:
        return []
    topics_set = set()
    try:
        with conn.cursor() as cur:
            # 1. From questions_repo
            cur.execute("SELECT DISTINCT topic FROM questions_repo WHERE category = %s;", (category,))
            for r in cur.fetchall():
                if r[0] and r[0].strip():
                    topics_set.add(r[0].strip())

            # 2. From learned_topics
            cur.execute("SELECT DISTINCT topic FROM learned_topics;")
            for r in cur.fetchall():
                if r[0] and r[0].strip():
                    topics_set.add(r[0].strip())
        return sorted(list(topics_set))
    except Exception as e:
        logger.error(f"db_get_all_community_topics error: {e}")
        return sorted(list(topics_set))
    finally:
        conn.close()


def db_save_lsrw_submission(
    player_id: str,
    module: str,
    topic: str,
    prompt_data: Dict[str, Any],
    user_submission: str,
    feedback: str,
    score: int,
    total: int
) -> bool:
    """
    Saves a complete LSRW submission record (task, submission, AI feedback, score)
    to Postgres for persistent review across sessions and deployments.
    """
    conn = _get_connection()
    if not conn:
        return False
    try:
        with conn.cursor() as cur:
            cur.execute("""
            INSERT INTO lsrw_submissions (player_id, module, topic, prompt_data, user_submission, feedback, score, total)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s);
            """, (
                player_id,
                module,
                topic,
                Json(prompt_data or {}),
                user_submission or "",
                feedback or "",
                score,
                total
            ))
        conn.commit()
        return True
    except Exception as e:
        logger.error(f"db_save_lsrw_submission error: {e}")
        conn.rollback()
        return False
    finally:
        conn.close()


def db_get_lsrw_submissions(player_id: str, module: str = None, limit: int = 30) -> List[Dict[str, Any]]:
    """
    Retrieves full submission history and AI corrections for a player.
    """
    conn = _get_connection()
    if not conn:
        return []
    try:
        with conn.cursor(cursor_factory=RealDictCursor) as cur:
            if module:
                cur.execute("""
                SELECT id, player_id, module, topic, prompt_data, user_submission, feedback, score, total, created_at
                FROM lsrw_submissions
                WHERE player_id = %s AND module = %s
                ORDER BY created_at DESC
                LIMIT %s;
                """, (player_id, module, limit))
            else:
                cur.execute("""
                SELECT id, player_id, module, topic, prompt_data, user_submission, feedback, score, total, created_at
                FROM lsrw_submissions
                WHERE player_id = %s
                ORDER BY created_at DESC
                LIMIT %s;
                """, (player_id, limit))
            rows = cur.fetchall()
            return [dict(r) for r in rows]
    except Exception as e:
        logger.error(f"db_get_lsrw_submissions error: {e}")
        return []
    finally:
        conn.close()


def db_clear_lsrw_submissions(player_id: str) -> bool:
    """Deletes all saved LSRW submissions for a player from Postgres."""
    conn = _get_connection()
    if not conn:
        return False
    try:
        with conn.cursor() as cur:
            cur.execute("DELETE FROM lsrw_submissions WHERE player_id = %s;", (player_id,))
        conn.commit()
        return True
    except Exception as e:
        logger.error(f"db_clear_lsrw_submissions error: {e}")
        conn.rollback()
        return False
    finally:
        conn.close()



