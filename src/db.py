"""
Database Service for German Goethe B1 Hub.
Supports PostgreSQL (Supabase / Neon.tech) with automatic table creation
and graceful offline fallback to local JSON.
"""
import os
import json
import logging
from typing import Dict, Any, List, Optional
from datetime import datetime

logger = logging.getLogger(__name__)

try:
    import psycopg2
    from psycopg2.extras import RealDictCursor, Json
    PSYCOPG2_AVAILABLE = True
except ImportError:
    PSYCOPG2_AVAILABLE = False


def get_database_url() -> str:
    """Returns database connection URL from Streamlit secrets, .env.local, or environment."""
    try:
        import streamlit as st
        if hasattr(st, "secrets"):
            if "DATABASE_URL" in st.secrets:
                return str(st.secrets["DATABASE_URL"]).strip()
            if "POSTGRES_URL" in st.secrets:
                return str(st.secrets["POSTGRES_URL"]).strip()
            if "postgres" in st.secrets and "url" in st.secrets["postgres"]:
                return str(st.secrets["postgres"]["url"]).strip()
            if "connections" in st.secrets and "postgresql" in st.secrets["connections"]:
                return str(st.secrets["connections"]["postgresql"].get("url", "")).strip()
    except Exception:
        pass

    # Check environment variable
    env_url = os.environ.get("DATABASE_URL") or os.environ.get("POSTGRES_URL")
    if env_url:
        return env_url.strip()

    # Check .env.local (generated by neon deploy) and .env
    for env_file in [".env.local", ".env"]:
        if os.path.exists(env_file):
            try:
                with open(env_file, "r", encoding="utf-8") as f:
                    for line in f:
                        line = line.strip()
                        if line and not line.startswith("#"):
                            for key in ["DATABASE_URL", "POSTGRES_URL", "DATABASE_AUTHENTICATED_URL"]:
                                if line.startswith(f"{key}="):
                                    val = line.split("=", 1)[1].strip().strip('"').strip("'")
                                    if val:
                                        return val
            except Exception:
                pass

    return ""


def is_db_connected() -> bool:
    """Checks whether a valid database connection can be established."""
    if not PSYCOPG2_AVAILABLE:
        return False
    url = get_database_url()
    if not url:
        return False
    try:
        conn = psycopg2.connect(url, connect_timeout=3)
        conn.close()
        return True
    except Exception:
        return False


def _get_connection():
    """Returns an active PostgreSQL database connection."""
    url = get_database_url()
    if not url:
        return None
    try:
        return psycopg2.connect(url, connect_timeout=5)
    except Exception as e:
        logger.warning(f"Database connection error: {e}")
        return None


def init_db():
    """Initializes tables in PostgreSQL if they do not exist."""
    conn = _get_connection()
    if not conn:
        return False

    try:
        with conn.cursor() as cur:
            # 1. Player Profiles
            cur.execute("""
            CREATE TABLE IF NOT EXISTS players (
                player_id VARCHAR(100) PRIMARY KEY,
                name VARCHAR(100) NOT NULL,
                avatar VARCHAR(20) DEFAULT '🦁',
                email VARCHAR(200) DEFAULT '',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            );
            """)

            # 2. Player Scores (Pronoun & Gender Duels, LSRW scores)
            cur.execute("""
            CREATE TABLE IF NOT EXISTS player_scores (
                id SERIAL PRIMARY KEY,
                player_id VARCHAR(100) NOT NULL,
                category VARCHAR(50) NOT NULL,
                score INT NOT NULL,
                total INT NOT NULL,
                topics TEXT DEFAULT '',
                date VARCHAR(20) NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            );
            """)

            # 3. Cumulative Learned Topics
            cur.execute("""
            CREATE TABLE IF NOT EXISTS learned_topics (
                id SERIAL PRIMARY KEY,
                player_id VARCHAR(100) NOT NULL,
                topic VARCHAR(200) NOT NULL,
                added_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                UNIQUE(player_id, topic)
            );
            """)

            # 4. AI Exercise Bank (Stores Gemini JSONs for Instant Re-take)
            cur.execute("""
            CREATE TABLE IF NOT EXISTS exercise_bank (
                id SERIAL PRIMARY KEY,
                module VARCHAR(50) NOT NULL,
                topic VARCHAR(200) NOT NULL,
                exercise_data JSONB NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            );
            """)

            # 5. Questions Repository (Stores generated questions per topic for continuous duels)
            cur.execute("""
            CREATE TABLE IF NOT EXISTS questions_repo (
                id SERIAL PRIMARY KEY,
                topic VARCHAR(200) NOT NULL,
                category VARCHAR(50) NOT NULL DEFAULT 'pronoun',
                question_data JSONB NOT NULL,
                created_by VARCHAR(100) DEFAULT 'ai',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            );
            """)

            # 6. LSRW Submissions and Full AI Corrections Archive
            cur.execute("""
            CREATE TABLE IF NOT EXISTS lsrw_submissions (
                id SERIAL PRIMARY KEY,
                player_id VARCHAR(100) NOT NULL,
                module VARCHAR(50) NOT NULL,
                topic VARCHAR(200) NOT NULL,
                prompt_data JSONB DEFAULT '{}',
                user_submission TEXT DEFAULT '',
                feedback TEXT DEFAULT '',
                score INT DEFAULT 0,
                total INT DEFAULT 10,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            );
            """)

            # Indexes for ultra-fast lookups
            cur.execute("""
            CREATE INDEX IF NOT EXISTS idx_scores_player ON player_scores(player_id);
            CREATE INDEX IF NOT EXISTS idx_scores_category ON player_scores(category);
            CREATE INDEX IF NOT EXISTS idx_bank_module_topic ON exercise_bank(module, topic);
            CREATE INDEX IF NOT EXISTS idx_qrepo_topic ON questions_repo(topic);
            CREATE INDEX IF NOT EXISTS idx_qrepo_category ON questions_repo(category);
            CREATE INDEX IF NOT EXISTS idx_lsrw_sub_player ON lsrw_submissions(player_id);
            CREATE INDEX IF NOT EXISTS idx_lsrw_sub_module ON lsrw_submissions(module);
            """)

        conn.commit()
        return True
    except Exception as e:
        logger.error(f"Error initializing database: {e}")
        conn.rollback()
        return False
    finally:
        conn.close()


